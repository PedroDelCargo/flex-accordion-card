export function localizeSchema(schema, hass) { return schema.map(field => ({ ...field, ...(field.selector?.select ? { selector: { ...field.selector, select: { ...field.selector.select, options: field.selector.select.options.map(option => typeof option === "string" ? option : { ...option, label: t(hass,option.label) }) } } } : {}), ...(field.schema ? { schema: localizeSchema(field.schema,hass) } : {}) })); }
